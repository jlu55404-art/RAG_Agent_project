# todo 本文件的用途：演示 BM25 算法的基本用法
# todo BM25 是一种经典的文本检索算法，可以理解成"搜索引擎怎么给搜索结果打分"
# todo 它计算查询词和每篇文档的"相关性分数"，分数越高说明越相关
# 1. rank_bm25 三方包
from rank_bm25 import BM25Okapi  # todo 导入 BM25 算法实现，BM25Okapi 是其中一种变体

# 2. 准备我们的文档库（随便你改）
documents = [  # todo 模拟一个文档库，里面有 5 篇文档（现实中可能是几万篇文章）
    "小猫在院子里开心地玩耍",
    "小猫今天吃了猫粮，然后睡了一天",
    "我喜欢小狗，小狗很可爱",
    "今天天气很好，适合出去玩",
    "小猫和小狗都是人类的好朋友"
]

# 3. 分词（中文按字切，英文按空格切都行）
# 这里简单用列表拆分
# 真实场景 jieba分词+BM25+Softmax归一化 准确度贼高
tokenized_docs = [list(doc) for doc in documents]  # 中文逐字拆分  # todo 把每篇文档的每个字拆成一个 token（比如"小猫玩耍"拆成['小','猫','玩','耍']）

# 4. 初始化 BM25 模型
bm25 = BM25Okapi(tokenized_docs)  # todo 用分词后的文档库初始化 BM25 模型，模型会计算每个词的统计信息

# 5. 输入你要搜索的词
query = "小猫 玩耍"  # todo 这是我们要搜索的关键词
tokenized_query = list(query)  # 查询也拆分  # todo 把查询词也拆成一个个 token

# 6. 计算每篇文档的 BM25 分数
scores = bm25.get_scores(tokenized_query)  # todo 计算查询词和每篇文档的相关性分数，分数越高的文档越相关

# 7. 输出结果
print("每篇文档的 BM25 分数：")
for i, score in enumerate(scores):
    print(f"文档{i + 1}：{documents[i]} → 分数：{score:.4f}")  # todo 打印每篇文档的分数，分数最高的就是最相关的文档

